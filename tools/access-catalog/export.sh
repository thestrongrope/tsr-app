#!/usr/bin/env bash
# Writes the permission catalog (permissions, role_permissions) as PostgreSQL SQL on stdout, derived from PHP.
# Source of truth: tsr-account's migrations (the files in build/parity-php/src/migrations, a git archive of develop).
# The parity stack's SYNTHETIC database already holds the catalog from PHP's reference seed, but that seed can lag the
# migrations (it lacked quiz:reset:all). So this script:
#   1. applies PHP's own catalog migrations that are idempotent (2026_10_22_quiz_reset_permission.sql) to that database,
#   2. dumps permissions and role_permissions,
#   3. refuses to continue if any permission name written in a PHP migration is missing from the dump.
# Usage (parity db up, tools/parity-php/README.md):  tools/access-catalog/export.sh > catalog.sql
# Regenerate when PHP adds permissions: run it, diff against the last catalog migration, put ONLY the new rows in a
# NEW access migration. Never edit an applied migration. Only the tsr-parity compose project is touched.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"
SRC=build/parity-php/src/migrations
parity() { docker compose -p tsr-parity -f tools/parity-php/compose.parity.yml --env-file tools/parity-php/parity.env "$@"; }
sql() { parity exec -T db sh -c 'mariadb -uroot -p"$MARIADB_ROOT_PASSWORD" tsr_synth -N -B'; }

sql < "$SRC/2026_10_22_quiz_reset_permission.sql" >&2

names="$(echo "select name from permissions order by name" | sql)"
for literal in $(grep -h -o "'[a-z-]*:[a-z-]*:[a-z]*'" "$SRC"/2026_*.sql | tr -d "'" | sort -u); do
  grep -qx "$literal" <<<"$names" || { echo "permission $literal is in a PHP migration but not in the database" >&2; exit 1; }
done

esc() { sed "s/'/''/g"; }
echo "-- Generated by tools/access-catalog/export.sh from PHP's catalog. Do not edit by hand."
echo "insert into access.permissions (name, description) values"
echo "select name, description from permissions order by name" | sql | esc \
  | awk -F'\t' '{printf "%s  ('"'"'%s'"'"', '"'"'%s'"'"')", (NR>1?",\n":""), $1, $2} END {print ""}'
echo "on conflict (name) do update set description = excluded.description;"
echo "insert into access.role_permissions (roleid, permission) values"
echo "select roleid, permission from role_permissions order by roleid, permission" | sql | esc \
  | awk -F'\t' '{printf "%s  (%s, '"'"'%s'"'"')", (NR>1?",\n":""), $1, $2} END {print ""}'
echo "on conflict do nothing;"
