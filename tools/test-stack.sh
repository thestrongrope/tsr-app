#!/usr/bin/env bash
# The synthetic TEST stack: docker-compose.dev.yml run as its own compose project, so contract tests have a database that
# never holds real data. It shares nothing with the dev stack (tsr-app-dev): containers, network and volumes are prefixed by
# the project name, and the published ports differ. The internal-only gotenberg PDF renderer has no host port.
# Usage: [TSR_STACK=n] tools/test-stack.sh up | down | remove | status
#   up      build and start (migrate and seed run once); waits for the API through the gateway
#   down    stop and delete the containers, KEEP the volume
#   remove  stop and delete the containers AND the volume (a clean database next time)
# Default (TSR_STACK unset): project tsr-app-test, gateway :8089, database :5434, Auth emulator :19100, docker-compose.test.yml.
# Lane stacks, so parallel agents (each in its own git worktree) have their own stack: TSR_STACK=n, n an integer 1 to 8:
#   project tsr-app-test-n, gateway 8100+n, database 5440+n, emulator 19110+n, tokens in build/test-n/ (the mapping is tools/stack-env.sh).
#   The ports are written literally into build/test-n/compose.override.yml from the validated integer. The stack builds from
#   the checkout this script lives in, so a worktree's lane runs that worktree's code. Contract scripts: TSR_STACK=n tools/<x>-contract.sh test.
# Only the selected tsr-app-test project is touched; every command carries -p <project>. All ports are 127.0.0.1 only.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
# shellcheck disable=SC1091
. tools/stack-env.sh

OVERRIDE="docker-compose.test.yml"
if [ -n "${TSR_STACK:-}" ]; then
  OVERRIDE="$TSR_TEST_VARS_DIR/compose.override.yml"
  mkdir -p "$TSR_TEST_VARS_DIR"
  cat > "$OVERRIDE" <<YML
# Generated by tools/test-stack.sh for TSR_STACK=$TSR_STACK. Literal ports, none of them dev's (8088, 5433, 19099).
services:
  db:
    ports: !override
      - "127.0.0.1:$TSR_TEST_DB_PORT:5432"
  firebase-emulator:
    ports: !override
      - "127.0.0.1:$TSR_TEST_EMULATOR_PORT:9099"
  gateway:
    ports: !override
      - "127.0.0.1:$TSR_TEST_GATEWAY_PORT:8080"
YML
fi

# The default test stack also runs Elasticsearch and the search-feed worker (compose profile "workers"); a lane stack does not
# (about 1 GB each), so its API answers every search "unavailable".
PROFILE=()
if [ -z "${TSR_STACK:-}" ]; then PROFILE=(--profile workers); fi
stack() { docker compose -p "$TSR_TEST_PROJECT" -f docker-compose.dev.yml -f "$OVERRIDE" ${PROFILE[@]+"${PROFILE[@]}"} "$@"; }

case "${1:?usage: test-stack.sh up|down|remove|status}" in
  up)
    stack up -d --build
    # nginx keeps the address of the API container it started with, and a single-file mount goes stale when git rewrites the file: after a rebuild the gateway must start again.
    stack restart gateway > /dev/null
    for _ in $(seq 1 60); do
      if curl -fsS --max-time 3 -o /dev/null "$TSR_TEST_BASE_URL/health"; then echo "test stack $TSR_TEST_PROJECT up on $TSR_TEST_BASE_URL"; exit 0; fi
      sleep 2
    done
    echo "test stack $TSR_TEST_PROJECT did not answer on $TSR_TEST_BASE_URL within 2 minutes" >&2; exit 1 ;;
  down) stack down ;;
  remove) stack down -v ;;
  status) stack ps ;;
  *) echo "usage: test-stack.sh up|down|remove|status" >&2; exit 1 ;;
esac
