"""Query + document embedding service for TSR lecture search.

Deliberately the *only* place embeddings are produced. Document vectors are
generated by POSTing to this same running service (not by loading the model in
a separate script): an identical model name loaded through a different library
can differ in pooling or normalization, which would put document vectors and
query vectors in different spaces and make cosine similarity meaningless.
"""

import os
from typing import List

from fastapi import FastAPI
from pydantic import BaseModel, Field

MODEL_NAME = os.environ.get("EMBEDDING_MODEL", "BAAI/bge-small-en-v1.5")
CACHE_DIR = os.environ.get("FASTEMBED_CACHE_PATH", "/opt/fastembed-cache")
MAX_TEXTS = int(os.environ.get("MAX_TEXTS_PER_REQUEST", "256"))

app = FastAPI(title="tsr-embeddings", version="1.0.0")

_model = None


def get_model():
    """Lazy singleton. The model is baked into the image, so this loads from
    the local cache and never reaches the network."""
    global _model
    if _model is None:
        from fastembed import TextEmbedding

        _model = TextEmbedding(model_name=MODEL_NAME, cache_dir=CACHE_DIR)
    return _model


class EmbedRequest(BaseModel):
    texts: List[str] = Field(..., min_length=1)
    # Routes to fastembed's query_embed/passage_embed. Verified to be a no-op
    # for BAAI/bge-small-en-v1.5 — fastembed applies no retrieval instruction
    # prefix, so both produce identical vectors. Kept because it is the library's
    # intended entry point and would take effect for a model that does prefix;
    # do not assume it is currently doing anything.
    mode: str = Field("passage", pattern="^(query|passage)$")


class TokenCountRequest(BaseModel):
    texts: List[str] = Field(..., min_length=1)


@app.get("/health")
def health():
    try:
        get_model()
        return {"status": "ok", "model": MODEL_NAME}
    except Exception as exc:  # pragma: no cover - surfaced via container health
        return {"status": "error", "model": MODEL_NAME, "error": str(exc)}


@app.post("/embed")
def embed(req: EmbedRequest):
    texts = req.texts[:MAX_TEXTS]
    model = get_model()
    embedder = model.query_embed if req.mode == "query" else model.passage_embed
    vectors = [v.tolist() for v in embedder(texts)]
    return {
        "vectors": vectors,
        "dim": len(vectors[0]) if vectors else 0,
        "model": MODEL_NAME,
        "mode": req.mode,
        "count": len(vectors),
    }


@app.post("/tokens")
def tokens(req: TokenCountRequest):
    """Real wordpiece token counts, plus the tokenizer's actual truncation limit.

    The model truncates silently, so an over-long document representation would
    quietly lose content with no error. Counting via the attention mask rather
    than len(ids) is essential: the tokenizer pads to a fixed width, so len(ids)
    reports the padded width for every input regardless of its real length.
    """
    model = get_model()
    try:
        tokenizer = model.model.tokenizer
        encodings = [tokenizer.encode(t) for t in req.texts]
        # attention_mask is 1 for real tokens and 0 for padding.
        counts = [int(sum(e.attention_mask)) for e in encodings]
        padded = [len(e.ids) for e in encodings]

        truncation = getattr(tokenizer, "truncation", None)
        max_tokens = truncation.get("max_length") if isinstance(truncation, dict) else None

        return {
            "counts": counts,
            "padded_widths": padded,
            "max_tokens": max_tokens,
            "exact": True,
        }
    except Exception as exc:
        counts = [max(1, int(len(t.split()) * 1.3)) for t in req.texts]
        return {"counts": counts, "max_tokens": None, "exact": False, "error": str(exc)}
